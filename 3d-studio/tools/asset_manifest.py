#!/usr/bin/env python3
"""3D Studio — the specimen asset & provenance manifest (MRB-186).

    python3 3d-studio/tools/asset_manifest.py           # write the manifest
    python3 3d-studio/tools/asset_manifest.py --check   # fail if it is stale

Writes docs/3d_studio_asset_manifest.md from the specimen records in
3d-studio/content/. Stdlib only, like every other harness in this folder.

WHY THIS FILE EXISTS
--------------------
The info panel used to end with a RECORD block carrying RENDERER, LICENCE,
SOURCE and ACQUIRED, visible to students in the default explore view behind no
flag. Ruled out on MRB-186: a student revising the heart has no use for any of
them, and `RENDERER: mesh` is the platform narrating its own internals on a
page whose job is to teach biology — the standing rule that student-facing
pages carry no explanatory meta-text about how the platform works.

But the ruling also said those values are genuinely useful, so they had to land
somewhere rather than be deleted. The choice was a developer-only view behind a
flag, or a manifest. This is the manifest, for three reasons:

  1. A dev flag is still student-facing code. It ships, it can be linked, and a
     wrong default turns it back on. A generated document has no runtime
     surface to regress.
  2. The question these rows answer is a PROCUREMENT question — "what are we
     hosting, under what licence, from whom?" — asked by a school business
     manager or a DPO about the whole collection at once. That is a document
     question. Nobody answers it by clicking through eight specimens in a
     revision app.
  3. Stage 10 requires an asset manifest anyway. This is that artefact,
     arriving early rather than being invented twice.

GENERATED, NEVER HAND-EDITED, so it cannot drift from the records it describes
— which is the failure mode a hand-written provenance list always eventually
has. `--check` re-renders and compares, so a stale manifest can fail a gate
instead of quietly lying.

It also carries the spec points, per hotspot, which is where MRB-193's
resolution rule becomes visible: a hotspot's own specPoints win, and it falls
back to the specimen's only where it declares none.
"""

import json
import os
import sys

STUDIO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO_ROOT = os.path.dirname(STUDIO_DIR)
CONTENT_DIR = os.path.join(STUDIO_DIR, "content")
OUT_PATH = os.path.join(REPO_ROOT, "docs", "3d_studio_asset_manifest.md")

BANNER = (
    "<!-- GENERATED by 3d-studio/tools/asset_manifest.py — do not hand-edit.\n"
    "     Change the specimen records in 3d-studio/content/ and re-run it. -->"
)


def is_todo(value):
    return isinstance(value, str) and value.startswith("TODO")


def cell(value):
    """A table cell that tells the truth about placeholders."""
    if value is None or value == "":
        return "—"
    if is_todo(value):
        return "_unauthored_"
    return str(value).replace("|", "\\|")


def load_records():
    files = sorted(
        f for f in os.listdir(CONTENT_DIR)
        if f.endswith(".json") and not f.endswith(".schema.json")
    )
    out = []
    for fname in files:
        with open(os.path.join(CONTENT_DIR, fname), encoding="utf-8") as fh:
            out.append((fname, json.load(fh)))
    return out


def render(records):
    lines = [
        BANNER,
        "",
        "# 3D Studio — specimen asset and provenance manifest",
        "",
        "Every 3D specimen the studio ships, what it is built from, where it",
        "came from and under what licence. Generated from the content records",
        "in `3d-studio/content/`; run",
        "`python3 3d-studio/tools/asset_manifest.py` to refresh it.",
        "",
        "This is the answer to a school's procurement and licensing question.",
        "It is deliberately **not** in the student-facing panel — see MRB-186.",
        "",
        "## Provenance",
        "",
        "| Specimen | Licence | Source | Acquired | Renderer |",
        "| --- | --- | --- | --- | --- |",
    ]
    for _fname, r in records:
        a = r.get("assets", {})
        lines.append("| %s (`%s`) | %s | %s | %s | `%s` |" % (
            cell(r.get("name")), r.get("id", "?"),
            cell(a.get("licence")), cell(a.get("source")),
            cell(a.get("acquired")), r.get("renderer", "?"),
        ))

    lines += ["", "## Files", "",
              "| Specimen | Mesh | 2D fallback | Thumbnail |",
              "| --- | --- | --- | --- |"]
    for _fname, r in records:
        a = r.get("assets", {})
        lines.append("| %s | %s | %s | %s |" % (
            cell(r.get("name")),
            cell(a.get("mesh")), cell(a.get("fallback")),
            cell(a.get("thumbnail")),
        ))

    lines += [
        "", "## Spec points", "",
        "A hotspot's own `specPoints` win where it declares them; where it",
        "does not, it inherits the specimen's (MRB-193). The *inherited*",
        "column below says which of the two is actually credited when a",
        "student answers about that structure.",
        "",
    ]
    for _fname, r in records:
        lines += [
            "### %s" % cell(r.get("name")),
            "",
            "Specimen default: %s" % (
                ", ".join("`%s`" % s for s in r.get("specPoints", []))
                if not any(is_todo(s) for s in r.get("specPoints", []))
                else "_unauthored_"),
            "",
            "| Structure | Spec points | Source | Accepted answers |",
            "| --- | --- | --- | --- |",
        ]
        for h in r.get("hotspots", []):
            own = h.get("specPoints")
            if isinstance(own, list) and own:
                pts = ", ".join("`%s`" % s for s in own)
                origin = "own"
            else:
                pts = "_(specimen default)_"
                origin = "inherited"
            accept = h.get("accept")
            acc = (", ".join(cell(x) for x in accept)
                   if isinstance(accept, list) and accept
                   else "_none authored — exact match on the label_")
            lines.append("| `%s` %s | %s | %s | %s |" % (
                h.get("id", "?"), cell(h.get("label")), pts, origin, acc))
        lines.append("")

    todo = sum(1 for _f, r in records
               for _p, v in _walk(r) if is_todo(v))
    lines += [
        "## Authoring state",
        "",
        "%d placeholder string(s) across %d record(s) still await Mide's "
        "Stage 8 science gate. `python3 3d-studio/validate_content.py` prints "
        "the itemised checklist." % (todo, len(records)),
        "",
    ]
    return "\n".join(lines) + "\n"


def _walk(node, path=""):
    if isinstance(node, dict):
        for k, v in node.items():
            yield from _walk(v, f"{path}.{k}" if path else k)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            yield from _walk(v, f"{path}[{i}]")
    elif isinstance(node, str):
        yield path, node


def main():
    if not os.path.isdir(CONTENT_DIR):
        print("❌ content directory not found: %s" % CONTENT_DIR)
        return 1
    records = load_records()
    if not records:
        print("❌ no specimen records in %s" % CONTENT_DIR)
        return 1

    text = render(records)
    rel = os.path.relpath(OUT_PATH, REPO_ROOT)

    if "--check" in sys.argv:
        if not os.path.exists(OUT_PATH):
            print("❌ %s does not exist — run this script without --check"
                  % rel)
            return 1
        with open(OUT_PATH, encoding="utf-8") as fh:
            current = fh.read()
        if current != text:
            print("❌ %s is STALE — a content record changed under it.\n"
                  "   Run: python3 3d-studio/tools/asset_manifest.py" % rel)
            return 1
        print("✅ %s is current (%d specimen record(s))" % (rel, len(records)))
        return 0

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("✅ wrote %s — %d specimen record(s): %s"
          % (rel, len(records), ", ".join(f for f, _r in records)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
