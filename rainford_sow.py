# ── the three ways a lesson can have no platform page ────────────────────

class Unmapped(object):
    """A deliberate non-mapping, carrying the reason it is one.

    This is the "None" the mapping dict could have used, with the why kept
    next to the what. A wrong slug points a teacher at the wrong lesson and
    says nothing; an Unmapped points at nothing and says why.
    """

    __slots__ = ("kind", "why")

    def __init__(self, kind, why):
        self.kind = kind
        self.why = why

    def __repr__(self):
        return "Unmapped(%r, %r)" % (self.kind, self.why)


ASSESSMENT = Unmapped(
    "assessment",
    "a test, quiz or review lesson — it teaches no new spec content, so no "
    "subtopic page corresponds to it")


def absent(why):
    """Real AQA content that the platform has no subtopic page for."""
    return Unmapped("absent", why)


def ambiguous(why):
    """Content that spans two or more subtopic pages with no clear primary."""
    return Unmapped("ambiguous", why)


