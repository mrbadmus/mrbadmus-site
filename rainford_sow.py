# ── SQL helpers ──────────────────────────────────────────────────────────

def q(s):
    """A SQL string literal, or NULL. Single quotes doubled, per the standard."""
    if s is None:
        return "null"
    return "'%s'" % str(s).replace("'", "''")


def school_id_sql(bare=False):
    """school_id by NAME, never a hardcoded uuid.

    uuids differ between the test project and production, so a seed carrying
    one is a seed that applies correctly in exactly one place. Looking the row
    up by its natural key makes the file portable, and a missing school then
    fails loudly on the NOT NULL rather than silently on a NULL subselect.

    `bare` drops the wrapping parentheses, for use as a CTE body.
    """
    sql = "select id from public.schools where name = %s" % q(SCHOOL_NAME)
    return sql if bare else "(%s)" % sql


def subject_id_sql(subject, bare=False):
    """subject_id by NAME — same reasoning as school_id_sql."""
    sql = ("select id from public.subjects where name = %s"
           % q(SUBJECT_TITLES[subject]))
    return sql if bare else "(%s)" % sql


# ── parsing ──────────────────────────────────────────────────────────────

def _cell(ws, row, col):
    """A cell's text, or None.

    ⚠️ Whitespace-only is None. The sheet has one cell holding a single space
    (row 123, Chemistry Foundation) and treating it as text invents a
    45th Year 11 Chemistry lesson with no title, no number and no unit.
    """
    v = ws.cell(row, col).value
    if v is None:
        return None
    v = str(v).strip()
    return v or None


def parse():
    """Every taught lesson in the workbook, one dict per (lesson, tier).

    Both sparse columns — the year in column A and each block's unit banner —
    are forward-filled, which is the only way to read a sheet a human wrote:
    the value is written once and means "and everything below, until the next
    one".
    """
    try:
        import openpyxl
    except ImportError:
        raise SystemExit(
            "rainford_sow: openpyxl is not installed. `pip3 install openpyxl` "
            "(3.1.5 is what this was written against).")

    if not os.path.isfile(WORKBOOK):
        raise SystemExit(
            "rainford_sow: cannot find the workbook at\n    %s\nIt is "
            "untracked and lives in the main checkout, not in a worktree."
            % WORKBOOK)

    wb = openpyxl.load_workbook(WORKBOOK, data_only=True)
    if SHEET not in wb.sheetnames:
        raise SystemExit(
            "rainford_sow: the workbook has no sheet %r. It has: %s. Note the "
            "trailing space in the expected name." % (SHEET, wb.sheetnames))
    ws = wb[SHEET]

    year = None
    unit = dict.fromkeys(SUBJECTS)
    out = []

    for r in range(2, ws.max_row + 1):          # row 1 is the header
        y = ws.cell(r, 1).value
        if y:
            year = int(str(y).strip().split()[-1])
        for subject in SUBJECTS:
            c_no, c_unit, c_high, c_found = COLUMNS[subject]
            u = _cell(ws, r, c_unit)
            if u:
                unit[subject] = u
            lesson_no = ws.cell(r, c_no).value
            entries = {"higher": _cell(ws, r, c_high),
                       "foundation": _cell(ws, r, c_found)}
            if lesson_no is None and not any(entries.values()):
                continue
            for tier in TIERS:
                text = entries[tier]
                if not text:
                    continue                     # HT-only lesson, or a gap
                out.append({
                    "year_group": year,
                    "subject": subject,
                    "tier": tier,
                    "lesson_no": int(lesson_no) if lesson_no else None,
                    "unit": unit[subject],
                    "text": text,
                })
    return out


# ── mapping ──────────────────────────────────────────────────────────────

def resolve(subject, unit, text):
    """(slug, unmapped) for one entry. Exactly one of the two is not None.

    Raises on an entry MAP has never seen. A lesson typed into the spreadsheet
    after this file was written must stop the run: silently emitting it with a
    NULL subtopic would look identical to a considered decision not to map it.
    """
    key = (subject, unit, text)
    if key in UNIT_MAP:
        return UNIT_MAP[key], None
    try:
        value = MAP[subject][text]
    except KeyError:
        raise SystemExit(
            "rainford_sow: %s entry %r (unit %r) is in the workbook but not "
            "in MAP. Add it — to a slug if it has a platform page, or to "
            "absent()/ambiguous()/ASSESSMENT if it does not. It must not be "
            "left to fall through." % (subject, text, unit))
    if isinstance(value, Unmapped):
        return None, value
    return value, None


def check_map(rows):
    """MAP and the workbook must describe the same set of lessons.

    Both directions matter. An entry with no key is caught in resolve(); a key
    with no entry is caught here, and is a mapping that has quietly stopped
    meaning anything — the lesson was renamed or deleted and the decision
    about it now applies to nothing.
    """
    seen = collections.defaultdict(set)
    for r in rows:
        seen[r["subject"]].add(r["text"])

    problems = []
    for subject in SUBJECTS:
        for text in MAP[subject]:
            if text not in seen[subject]:
                problems.append(
                    "MAP[%r] has %r, which no longer appears in the workbook"
                    % (subject, text))
    for (subject, unit, text) in UNIT_MAP:
        if text not in seen[subject]:
            problems.append(
                "UNIT_MAP names %s %r (unit %r), which no longer appears in "
                "the workbook" % (subject, text, unit))
    if problems:
        raise SystemExit(
            "rainford_sow: %d stale mapping(s)\n  · %s"
            % (len(problems), "\n  · ".join(problems)))


def check_slugs():
    """Every slug in MAP must be a real KS4 subtopic OF THAT SUBJECT.

    `ks4_data.classify()` is the site's own curriculum projection, so this
    checks the mapping against the pages that actually exist rather than
    against a second list that could drift from them. The subject check is the
    one that catches a copy-paste between blocks: `chromatography` is a real
    slug, and it is not a physics one.
    """
    cls = ks4_data.classify()
    problems = []
    for subject in SUBJECTS:
        for text, value in MAP[subject].items():
            if isinstance(value, Unmapped):
                continue
            meta = cls.get(value)
            if meta is None:
                problems.append("%s %r → %r is not a KS4 subtopic slug"
                                % (subject, text, value))
            elif meta["subject"] != subject:
                problems.append(
                    "%s %r → %r, which is a %s subtopic"
                    % (subject, text, value, meta["subject"]))
    for (subject, unit, text), value in UNIT_MAP.items():
        meta = cls.get(value)
        if meta is None or meta["subject"] != subject:
            problems.append("UNIT_MAP %s/%s %r → %r is not a %s subtopic"
                            % (subject, unit, text, value, subject))
    if problems:
        raise SystemExit(
            "rainford_sow: %d bad slug(s)\n  · %s"
            % (len(problems), "\n  · ".join(problems)))


def check_shape(rows):
    """The parsed sheet must still have the shape it was mapped against."""
    counts = collections.Counter()
    for r in rows:
        if r["tier"] == "higher":
            counts[(r["year_group"], r["subject"])] += 1
    if dict(counts) != EXPECTED_ROWS:
        raise SystemExit(
            "rainford_sow: the workbook's shape has changed.\n  expected %s\n"
            "  got      %s\nRe-read the sheet before trusting the mapping."
            % (sorted(EXPECTED_ROWS.items()), sorted(counts.items())))


def check_triple_prefix(rows):
    """Does "(BIO)"/"(CHEM)"/"(PHYS)" really mean Triple-only?

    The brief that commissioned this file said the prefixes *appear* to mark
    Triple-only content and asked for the reading to be verified rather than
    assumed. This measures it: for every prefixed entry that maps to a
    subtopic, does the site independently flag that subtopic `triple_only`?

    Returns (prefixed_total, prefixed_agreeing, unprefixed_but_triple), which
    main() prints. It never raises — the prefix is Rainford's notation, not a
    platform invariant, and a disagreement is a finding for the report rather
    than a broken build.
    """
    cls = ks4_data.classify()
    prefixed = prefixed_triple = unprefixed_triple = 0
    seen = set()
    for r in rows:
        key = (r["subject"], r["text"])
        if key in seen:
            continue
        seen.add(key)
        slug, _ = resolve(r["subject"], r["unit"], r["text"])
        if slug is None:
            continue
        marked = r["text"].lstrip().startswith(("(BIO)", "(CHEM)", "(PHYS)"))
        triple = cls[slug]["triple_only"]
        if marked:
            prefixed += 1
            prefixed_triple += int(triple)
        elif triple:
            unprefixed_triple += 1
    return prefixed, prefixed_triple, unprefixed_triple


# ── building the blocks ──────────────────────────────────────────────────

def build(rows):
    """(year, subject, tier) → the block's rows, renumbered from 1.

    The sheet is already in teaching order, so "renumber" is literally
    enumerate: the nth entry of a block is that block's nth taught lesson.
    """
    blocks = collections.OrderedDict()
    for year in YEARS:
        for subject in SUBJECTS:
            for tier in TIERS:
                block = [r for r in rows
                         if r["year_group"] == year
                         and r["subject"] == subject
                         and r["tier"] == tier]
                if not block:
                    continue
                if len(block) > MAX_ACADEMIC_WEEK:
                    raise SystemExit(
                        "rainford_sow: Year %d %s %s has %d lessons and "
                        "academic_week's KS4 ceiling is %d. The ceiling is a "
                        "database CHECK — raise it in a migration first."
                        % (year, subject, tier, len(block),
                           MAX_ACADEMIC_WEEK))
                out = []
                for week, r in enumerate(block, start=1):
                    slug, unmapped = resolve(r["subject"], r["unit"],
                                             r["text"])
                    note = "L%s · %s" % (r["lesson_no"] or "?", r["text"])
                    if unmapped is not None:
                        note += "  [no subtopic: %s]" % unmapped.kind
                    out.append(dict(r, academic_week=week, subtopic=slug,
                                    unmapped=unmapped, notes=note))
                blocks[(year, subject, tier)] = out
    return blocks


def unmapped_entries(blocks):
    """Every distinct unplaced lesson, in teaching order, with its tiers.

    Deduplicated on (year, subject, lesson number, text): a lesson whose two
    columns hold the same words is one lesson, and listing it twice would
    overstate the gap.
    """
    seen = collections.OrderedDict()
    for (year, subject, tier), rows in blocks.items():
        for r in rows:
            if r["unmapped"] is None:
                continue
            key = (year, subject, r["lesson_no"], r["text"])
            entry = seen.setdefault(key, dict(r, tiers=[]))
            entry["tiers"].append(tier)
    return list(seen.values())


