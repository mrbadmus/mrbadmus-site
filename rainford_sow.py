def main():
    print("\nrainford_sow — Rainford High School's KS4 scheme, as override "
          "rows\n" + "=" * 70)

    os.makedirs(SEED_DIR, exist_ok=True)

    rows = parse()
    check_shape(rows)
    check_slugs()
    check_map(rows)

    blocks = build(rows)
    unplaced = unmapped_entries(blocks)
    triple_stats = check_triple_prefix(rows)

    path = os.path.join(SEED_DIR, SEED_FILE)
    with open(path, "w", encoding="utf-8") as f:
        f.write(render(blocks, unplaced, triple_stats))

    _report(path, rows, blocks, unplaced, triple_stats)
    return 0


def _report(path, rows, blocks, unplaced, triple_stats):
    total = sum(len(v) for v in blocks.values())
    placed = total - sum(1 for v in blocks.values() for r in v
                         if r["unmapped"] is not None)
    prefixed, agreeing, unprefixed_triple = triple_stats

    print("\n  workbook  ← %s" % WORKBOOK)
    print("  written   → %s\n" % path)

    print("  %-6s %-9s %-11s %7s %7s" % ("year", "subject", "tier", "rows",
                                         "max wk"))
    for (year, subject, tier), block in blocks.items():
        print("  %-6s %-9s %-11s %7d %7d"
              % ("Y%d" % year, SUBJECT_TITLES[subject], tier, len(block),
                 max(r["academic_week"] for r in block)))

    print("\n  %d rows · %d with a subtopic · %d without"
          % (total, placed, total - placed))
    print("  taught lessons in the sheet: %d (Higher %d, Foundation %d)"
          % (len(rows),
             sum(1 for r in rows if r["tier"] == "higher"),
             sum(1 for r in rows if r["tier"] == "foundation")))
    print("  ceiling %d per block (table CHECK); largest block %d."
          % (MAX_ACADEMIC_WEEK,
             max(len(v) for v in blocks.values())))

    print("\n  Triple prefix check: %d mapped entries carry (BIO)/(CHEM)/"
          "(PHYS);" % prefixed)
    print("    %d of those map to a triple_only subtopic; %d unprefixed "
          "entries do too." % (agreeing, unprefixed_triple))

    by_kind = collections.Counter(e["unmapped"].kind for e in unplaced)
    print("\n  ⚠️ UNMAPPED — %d distinct lessons (%s):"
          % (len(unplaced),
             ", ".join("%s %d" % (k, by_kind[k]) for k in sorted(by_kind))))
    subject = year = None
    for e in unplaced:
        if e["unmapped"].kind == "assessment":
            continue
        if (e["year_group"], e["subject"]) != (year, subject):
            year, subject = e["year_group"], e["subject"]
            print("     ── Year %d · %s ──" % (year, SUBJECT_TITLES[subject]))
        print("       L%-4s [%s]  %s"
              % (e["lesson_no"] or "?", e["unmapped"].kind, e["text"]))
    print("     (%d assessment/review lessons omitted from this list; they "
          "are\n      all named in the SQL.)" % by_kind.get("assessment", 0))


