-- MRB-331 — SET WORK v1. What an assignment must carry once a teacher can make one.
--
-- ⚠️ VERSION IS LOAD-BEARING. Applied to TEST through MCP `apply_migration`,
-- which records its OWN `schema_migrations` version rather than reading a
-- filename. TEST recorded 20260906144742, so this file carries it. Renaming it
-- makes `supabase db push` re-apply the whole thing on the next run.
--
-- Until now every assignment in the estate was produced the same way: the
-- first student through the door for a (class, week) triggered composition
-- from `scheme_of_work_entries`. `auto_generated` recorded that, and it was
-- true on every row because there was no other kind. This adds the other kind.

-- ── 1. `source` — the authority on where an assignment came from ───────
--
-- `auto_generated` already answers this, so adding `source` risks two columns
-- disagreeing. They are tied by a CHECK below rather than left to discipline,
-- because every existing reader of `auto_generated` (the API payload, the
-- teacher tables, the consumer path) keeps working unchanged only for as long
-- as the two agree. The CHECK makes disagreement impossible, not unlikely.
alter table public.assignments
  add column if not exists source text not null default 'auto';

alter table public.assignments
  drop constraint if exists assignments_source_check;
alter table public.assignments
  add constraint assignments_source_check
  check (source in ('auto', 'teacher'));

-- Backfill from `auto_generated`, which is the only record that exists of how
-- a row was made. NULL there means "written before the column existed", which
-- was also auto.
--
-- ⚠️ THIS LABELS PRE-EXISTING HAND-SEEDED ROWS 'teacher', and that was
-- measured before it was accepted. The rows it touches are fixture and demo
-- assignments with no `set_by` — so they will render with no author, which is
-- true. What matters operationally is whether the label moves a row out of
-- `assignments_class_week_uniq` below, and it does not: every such row already
-- carries `academic_week IS NULL` and was therefore already outside that
-- partial index. Verified on both projects before applying —
--
--   select count(*) filter (where auto_generated is false
--                             and academic_week is not null) as would_leave_index
--   from assignments where deleted_at is null;
--
-- TEST: 0 of 34.  PROD: 0 of 2.  Re-run it before the production apply; a
-- non-zero answer means a real auto row would lose its uniqueness guard and
-- this migration must not go in as written.
update public.assignments
  set source = case when auto_generated is false then 'teacher' else 'auto' end
  where source is distinct from
        (case when auto_generated is false then 'teacher' else 'auto' end);

alter table public.assignments
  drop constraint if exists assignments_source_agrees_with_auto_generated;
alter table public.assignments
  add constraint assignments_source_agrees_with_auto_generated
  check ((source = 'auto') = coalesce(auto_generated, true));

-- ── 2. `set_by` — WHO set it ───────────────────────────────────────────
--
-- Distinct from `teacher_id`, which on an auto row is whichever teacher
-- happens to come first out of `class_teachers` (see `classSubjectId()`) —
-- a filing detail, not an author. `set_by` is null on every auto row and is
-- the acting teacher on every teacher-set one.
alter table public.assignments
  add column if not exists set_by uuid references public.profiles(id);

-- ── 3. `release_at` — when it reaches the student ──────────────────────
--
-- NULL means "already released", which is what every existing row is and must
-- stay: an auto assignment is composed at the moment it is first needed, so it
-- has no release to wait for. Only teacher-set work carries a stamp.
--
-- The school-wide hold (`schools.assignments_open_from`) is deliberately NOT
-- read here. It is resolved at SET time into this value —
-- `release_at = greatest(what the teacher chose, the school's open-from date)`
-- — for the same reason MRB-324 put the hold on the creation path and not the
-- serving path: a hold moved later must never retract work a student can
-- already see.
alter table public.assignments
  add column if not exists release_at timestamptz;

comment on column public.assignments.source is
  'auto = composed from the scheme by the producer; teacher = set by a named teacher on the Set work sheet (MRB-331). Tied to auto_generated by a CHECK.';
comment on column public.assignments.set_by is
  'The teacher who set this work. NULL on every auto row. Not teacher_id, which on an auto row is a filing detail.';
comment on column public.assignments.release_at is
  'When this reaches students. NULL = already released (every auto row). Resolved against schools.assignments_open_from at set time, never at read time.';

-- ── 4. The per-class-per-week uniqueness becomes AUTO-ONLY ─────────────
--
-- ⚠️ THIS IS THE CHANGE THAT CAN BREAK A LIVE READ, and the index is only
-- half of it. `/api/class/current-assignment` finds the week's work with
-- `.eq('class_id').eq('academic_week').maybeSingle()`. The moment a class
-- holds an auto AND a teacher-set assignment in the same week — the entire
-- point of this ticket — that returns two rows and PostgREST turns
-- `maybeSingle()` into an error for every student in the class. The three
-- lookups in `server.js` (the composed-branch check at 1047, the 23505
-- re-read at 1175, and /api/class/progress at 3527) all gain
-- `.eq('source', 'auto')`, and they ship in the same unit as this file.
--
-- Teacher-set work still carries a real `academic_week`: it is what puts it in
-- the class screen's week bar, in Today, and in the digest alongside the auto
-- work. Dropping the week to dodge the constraint would have left the index
-- untouched and made the work invisible to every week-scoped surface.
drop index if exists public.assignments_class_week_uniq;
create unique index if not exists assignments_class_week_uniq
  on public.assignments (class_id, academic_week)
  where deleted_at is null and academic_week is not null and source = 'auto';

-- ── 5. `classes.auto_assignments` — the per-class producer switch ──────
--
-- Rainford runs Sparx. A class that has switched the automatic weekly work off
-- still gets everything else: teacher-set work, marking, feedback, reminders,
-- the leaderboard. Only composition stops.
alter table public.classes
  add column if not exists auto_assignments boolean not null default true;

comment on column public.classes.auto_assignments is
  'false stops the weekly producer composing for this class (MRB-331). Nothing else changes: teacher-set work, marking, feedback and reminders are unaffected.';

-- The student''s week card asks "what has been released to this class", which
-- is a (class_id, release_at) question and had no index behind it.
create index if not exists assignments_class_release_idx
  on public.assignments (class_id, release_at)
  where deleted_at is null;
