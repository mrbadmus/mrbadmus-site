resolved as (
  select s.staff_code, s.weekday, s.period,
         c.id as class_id, c.school_id, c.academic_year_id,
         ps.id as pending_staff_id,
         case when s.staff_code = 'BDA' then p.id end as teacher_id
    from src s
    join public.academic_years ay on ay.name = '2026-27'
    join public.classes c on c.name = s.class_name
                         and c.academic_year_id = ay.id
                         and c.deleted_at is null
    left join public.pending_staff ps on ps.staff_code = s.staff_code
                                     and ps.deleted_at is null
    left join public.profiles p on s.staff_code = 'BDA'
