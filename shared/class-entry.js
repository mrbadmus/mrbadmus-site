/* ───────────────────────────────────────────────────────────────────────
   shared/class-entry.js — the door to a student's class (MRB-259)

   Everything built for the schools layer — quiz capture at both grains,
   student/assignment.html, the teacher's class detail and Stars leaderboard —
   hangs off student/class.html, and until this file existed NOTHING on the
   site linked to it. It requires ?class=<uuid> and there was no href to it
   anywhere in the repo, so a Year 8 signing in had no route to their own
   homework.

   ── Mide's ruling, 19 Aug 2026 ──────────────────────────────────────────
   A class is a property of the PERSON, not of a key stage. The entry is
   global and identity-scoped and does NOT sit behind the KS3/KS4 chooser: a
   Year 8 should not have to know they are "KS3" to find their homework. Their
   key stage is already known from their class membership, so the platform
   routes them.

     · signed out                 → nothing rendered, ever
     · signed in, zero classes    → nothing rendered (self-serve visitors are
                                    never offered a page that would reject them)
     · signed in, exactly one     → links STRAIGHT to it, uuid already in the
                                    href; no intermediate page, nothing typed
     · signed in, more than one   → links to the picker, /student/classes.html
     · staff                      → the equivalent, /teacher/classes.html

   ── Why this module renders, and nav.js does not ────────────────────────
   The site has THREE nav worlds and this entry belongs in all of them:

     1. KS3 pages       — .ks3-nav-rail, generated by build_ks3.py. Its own
                          design world: one #E4572E chevron, no 3D Studio, no
                          auth surface at all before this file.
     2. Public / KS4    — .nav-cluster, markup from generate_site_v5.py,
                          behaviour from shared/nav.js.
     3. Dashboards      — nav.top-nav, hand-written per page.

   Putting the KS4 half in nav.js and the rest here would split one feature
   across two files AND create a load-order dependency (both are `defer`, so
   execution follows document order and a mis-ordered <script> would silently
   drop the entry). Instead this module owns all three renders and touches
   nav.js not at all. It is order-independent by construction: every render
   happens AFTER a network round-trip, so nav.js has long since built its
   drawer by the time we look for it.

   ── No flash, guaranteed structurally ───────────────────────────────────
   A signed-out visitor must never see the entry appear and then vanish. That
   is guaranteed by the shape of this file rather than by a CSS rule: the
   markup does not exist in any page's HTML, and it is only ever CREATED once
   the viewer is known to be signed in AND enrolled. There is no state in
   which it is present and then removed.

   ── Environment ─────────────────────────────────────────────────────────
   Uses window.MrBadmusConfig when the page loads shared/config.js (the
   dashboards do, and they honour ?env=test), and falls back to the production
   constants when it does not (KS3 and the public pages load neither the SDK
   nor config.js — this module must not require them). Same PostgREST-over-
   fetch approach shared/nav.js already uses, for the same reason: no build
   step, no SDK on most of the site.
   ─────────────────────────────────────────────────────────────────────── */
(function () {
  'use strict';

  // Production, matching shared/config.js's PROD block. Anon keys are designed
  // to be public; RLS is the actual gate and every query below is scoped to
  // the viewer's own rows anyway.
  var PROD_URL = 'https://urklkrwevjtlfbwnipjn.supabase.co';
  var PROD_KEY = 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6InVya2xrcndldmp0bGZid25pcGpuIiwicm9sZSI6ImFub24iLCJpYXQiOjE3NzQxOTQyNzksImV4cCI6MjA4OTc3MDI3OX0.pW9AP6TPlKC_XHDTbrEKrEGmGXglN0z5b0KGXD2oHvg';

  var CACHE_PREFIX = 'mrb-class-entry:v2:';   // v2: year-scoped (MRB-261)
  /* 30 min. It was 10, and the entry it caches answers ONE question — which
     class page to link to — which changes only when a teacher enrols or
     removes somebody. A lesson is an hour, so 30 minutes still surfaces a
     mid-session enrolment inside the same lesson (the property the 10 was
     chosen for) while cutting the re-resolve from six round trips an hour to
     two on a student walking the 294 KS3 pages. */
  var CACHE_TTL_MS = 30 * 60 * 1000;

  var YEARS_CACHE_PREFIX = 'mrb-academic-years:v1:';
  /* The same 30 minutes, for a list that moves once a year. It is scoped to
     the SCHOOL rather than the viewer because `academic_years` is readable by
     any member of the school and the rows are identical for all of them — but
     it is keyed on the viewer anyway, because a shared browser signing a
     second student in must not read the first one's answer through RLS's
     back. Session-scoped storage, so it dies with the tab either way. */
  var YEARS_TTL_MS = 30 * 60 * 1000;

  /* ── The working academic year (MRB-261) ────────────────────────────────
     Which year's classes are the ones that matter right now.

     NOT `academic_years.is_current`. That flag is moved by hand on 1
     September (MRB-237), so for the whole of late August it still points at
     the year that finished in July. Scoping on it in August would show a
     Year 11 their Year 10 class and hide the one they start in a fortnight
     — the exact inverse of the bug this fixes.

     NOT a plain `end_date >= today` either. 2025-26 runs to 31 Aug 2026, so
     on 19 Aug BOTH years are unfinished, both match, and the student is
     offered two classes. That IS the bug.

     The rule: a year has effectively finished once it has less than
     YEAR_LOOKAHEAD_DAYS left to run, and the working year is the EARLIEST
     year still running past that horizon. In plain English, "the year we
     will be in a month from now". The horizon only ever crosses a boundary
     inside the last month of an academic year — i.e. during the summer
     holiday, which is exactly the stretch where "this year" is ambiguous
     and where forward-looking is what a school actually means.

       19 Aug 2026   horizon 18 Sep 2026   2025-26 ends 31 Aug -> out  -> 2026-27
       31 Aug 2026   horizon 30 Sep 2026   2025-26 ends 31 Aug -> out  -> 2026-27
        1 Sep 2026   horizon  1 Oct 2026   2025-26 already ended       -> 2026-27
       15 Jan 2027   horizon 14 Feb 2027   2026-27 running, earliest   -> 2026-27
       15 Jul 2027   horizon 14 Aug 2027   2026-27 running, earliest   -> 2026-27
       19 Aug 2027   horizon 18 Sep 2027   2026-27 ends 31 Aug -> out  -> 2027-28

     Fallback: if no year clears the horizon (a school whose next year has
     not been created yet) use the latest year that exists, so the page shows
     what there is rather than nothing.

     Dates are ISO `YYYY-MM-DD` from Postgres `date` columns, so string
     comparison IS date comparison — no parsing, no timezone to get wrong.

     ⊕ MRB-267, 19 Aug 2026 — THIS IS NOW THE ONLY COPY. It used to say "kept
     in sync by hand with the identical helper in shared/student-data.js and
     shared/teacher-data.js", and hand-syncing three copies of a date
     predicate is a bug waiting for the 1st of September. The other two are
     deleted; both files call `window.MRBClassEntry.workingAcademicYear`.

     ⚠️ THE DEPENDENCY RUNS ONE WAY ONLY. This file stays dependency-free —
     it loads on all 294 KS3 pages, which pull neither the SDK nor config.js
     — so it cannot import anything. The data layers depend on IT, never the
     reverse, and they resolve the reference AT CALL TIME rather than at load
     time. That is load-bearing: this module is `defer`red on all four
     dashboard pages and the data layers are not, so this file EXECUTES LAST.
     Every call site is behind an `await` on a Supabase query, so the module
     is always present by the time the predicate is asked — checked at all
     four, not assumed.
     ───────────────────────────────────────────────────────────────────── */
  var YEAR_LOOKAHEAD_DAYS = 30;

  function pad2(n) { return (n < 10 ? '0' : '') + n; }

  function lookaheadDate() {
    var d = new Date();
    d.setDate(d.getDate() + YEAR_LOOKAHEAD_DAYS);
    return d.getFullYear() + '-' + pad2(d.getMonth() + 1) + '-' + pad2(d.getDate());
  }

  function workingAcademicYear(years) {
    var rows = (years || []).filter(function (y) { return y && y.end_date; });
    if (!rows.length) return null;
    var horizon = lookaheadDate();
    var live = rows.filter(function (y) { return y.end_date >= horizon; });
    if (live.length) {
      return live.reduce(function (best, y) {
        return (!best || y.end_date < best.end_date) ? y : best;
      }, null);
    }
    return rows.reduce(function (best, y) {
      return (!best || y.end_date > best.end_date) ? y : best;
    }, null);
  }

  function cfg() {
    var c = window.MrBadmusConfig;
    if (c && c.SUPABASE_URL && c.SUPABASE_ANON_KEY) {
      return { url: c.SUPABASE_URL, key: c.SUPABASE_ANON_KEY,
               env: c.environment || 'prod' };
    }
    return { url: PROD_URL, key: PROD_KEY, env: 'prod' };
  }

  // Project ref out of the URL — the localStorage session key is
  // `sb-<ref>-auth-token`, so this is what makes the module work against
  // test and prod without being told which it is on.
  function projectRef(url) {
    var m = /^https:\/\/([a-z0-9]+)\.supabase\.co/i.exec(url || '');
    return m ? m[1] : '';
  }

  // The stored session. Newer supabase-js versions may wrap the JSON in a
  // `base64-` envelope; older ones store it plain. Handle both rather than
  // assuming the version the CDN happens to serve today.
  function readSession(ref) {
    try {
      var raw = localStorage.getItem('sb-' + ref + '-auth-token');
      if (!raw) return null;
      if (raw.indexOf('base64-') === 0) {
        raw = decodeURIComponent(escape(atob(raw.slice(7))));
      }
      var s = JSON.parse(raw);
      if (!s || !s.access_token || !s.user || !s.user.id) return null;
      // An expired stored session would 401 on every query below; treat it as
      // signed out rather than rendering an entry that leads nowhere.
      var expMs = s.expires_at ? s.expires_at * 1000 : 0;
      if (expMs && expMs <= Date.now()) return null;
      return s;
    } catch (e) { return null; }
  }

  function rest(conf, session, path) {
    return fetch(conf.url + '/rest/v1/' + path, {
      headers: {
        'apikey': conf.key,
        'Authorization': 'Bearer ' + session.access_token,
        'Accept': 'application/json'
      }
    }).then(function (r) { return r.ok ? r.json() : null; })
      .catch(function () { return null; });
  }

  function cacheGet(key, ttl) {
    try {
      var raw = sessionStorage.getItem(key);
      if (!raw) return null;
      var box = JSON.parse(raw);
      if (!box || typeof box.t !== 'number') return null;
      if (Date.now() - box.t > (ttl || CACHE_TTL_MS)) return null;
      return box.v;                      // may legitimately be null ("nothing
                                         // to show"), which is worth caching
                                         // just as much as a positive answer.
    } catch (e) { return null; }
  }

  function cacheSet(key, value) {
    try {
      sessionStorage.setItem(key, JSON.stringify({ t: Date.now(), v: value }));
    } catch (e) {}
  }

  /* ── The academic years, read ONCE per page ─────────────────────────────
     ⊕ 27 Aug 2026 — the load-performance pass.

     `academic_years` was being read TWICE on every dashboard load, ~200ms
     apart and in two different waves: once here, to year-scope the nav entry,
     and once again by `teacher-data.loadAcademicYears()` / the equivalent read
     inside `student-data.loadStudentClasses()`. Two answers to a settled
     question, and the second one arrives after the first has already been
     used, so it can only ever agree or be a bug.

     This file already owns the ONE `workingAcademicYear` predicate (MRB-267),
     for exactly the reason that three hand-synced copies of a date rule is a
     bug waiting for the 1st of September. It should equally own the ONE read
     the predicate is applied to. The dependency still runs one way only: the
     data layers reach for `window.MRBClassEntry` at CALL time and this file
     imports nothing.

     ⚠️ IT RESOLVES TO NULL RATHER THAN THROWING, and callers must treat null
     as "I do not know" and NOT as "there are no years". `rest()` swallows a
     network failure into null, and a caller that read null as an empty list
     would drop the year filter entirely — which shows a Year 11 the class
     they left in July, the precise bug MRB-261 fixed. Both data layers fall
     back to their own query on null. */
  var _yearsInflight = null;

  function academicYears() {
    if (_yearsInflight) return _yearsInflight;
    _yearsInflight = (function () {
      var conf = cfg();
      var ref = projectRef(conf.url);
      if (!ref) return Promise.resolve(null);
      var session = readSession(ref);
      if (!session) return Promise.resolve(null);   // signed out → no read

      var key = YEARS_CACHE_PREFIX + conf.env + ':' + session.user.id;
      var hit = cacheGet(key, YEARS_TTL_MS);
      if (hit) return Promise.resolve(hit);

      return rest(conf, session,
                  'academic_years?deleted_at=is.null' +
                  '&select=id,name,start_date,end_date&order=start_date.asc')
        .then(function (rows) {
          // Only a POSITIVE answer is cached. An empty array from a school
          // with no years yet is indistinguishable here from a query that was
          // refused, and caching the second for half an hour would pin a
          // dashboard to the wrong scope for the rest of the session.
          if (rows && rows.length) { cacheSet(key, rows); }
          return rows;
        });
    })();
    return _yearsInflight;
  }

  /* ── Resolution ──────────────────────────────────────────────────────────
     Returns a promise for { href, label, title } or null (render nothing). */
  var _inflight = null;

  /* Staff surfaces, where the viewer CANNOT be a student — every one of these
     pages opens with a role guard that sends a student home. See below. */
  function onStaffSurface() {
    var p = window.location.pathname || '';
    return p.indexOf('/teacher/') === 0 ||
           p.indexOf('/admin/') === 0 ||
           p.indexOf('/hod/') === 0;
  }

  function resolve() {
    if (_inflight) return _inflight;
    _inflight = (function () {
      var conf = cfg();
      var ref = projectRef(conf.url);
      if (!ref) return Promise.resolve(null);

      var session = readSession(ref);
      if (!session) return Promise.resolve(null);   // signed out → nothing

      var cacheKey = CACHE_PREFIX + conf.env + ':' + session.user.id;
      var cached = cacheGet(cacheKey);
      if (cached !== null) return Promise.resolve(cached);

      var uid = encodeURIComponent(session.user.id);

      /* Role, membership and the school's academic years in parallel. A
         teacher is never a class_member, so the first two answers can't both
         be positive; asking for all three at once still costs one round trip.
         academic_years is readable by any member of the school
         (academic_years_member_read), so this needs no new grant — and since
         27 Aug it goes through `academicYears()` above, so the dashboards read
         that list once rather than twice.

         ⊕ 27 Aug 2026 — THE MEMBERSHIP QUERY IS SKIPPED ON STAFF SURFACES.
         `class_members?student_id=eq.<uuid>` with a TEACHER's uuid in it can
         never match a row: `student_id` references a student and a teacher is
         linked through `class_teachers`. It was firing on every teacher
         dashboard load anyway, inside the cold-connection wave the whole page
         was queuing behind, to answer a question whose answer was structurally
         empty. It is skipped by SURFACE rather than by role because role only
         arrives with the first response — and every `/teacher/*`, `/admin/*`
         and `/hod/*` page opens with a guard that sends a student home, so a
         viewer who reaches one either is staff or is about to be redirected.
         Everywhere else — KS3, KS4, the public pages, `/student/*` — the
         question is real and all three still go together. */
      var wantMembership = !onStaffSurface();

      return Promise.all([
        rest(conf, session, 'profiles?id=eq.' + uid + '&select=role'),
        wantMembership
          ? rest(conf, session,
                 'class_members?student_id=eq.' + uid +
                 '&left_at=is.null&deleted_at=is.null&select=class_id')
          : Promise.resolve([]),
        academicYears()
      ]).then(function (res) {
        var roleRows = res[0], memberRows = res[1], yearRows = res[2];
        var role = (roleRows && roleRows[0] && roleRows[0].role) || null;

        // Staff get the equivalent entry, pointing at their own classes page.
        // Rendered on role alone: teacher/classes.html owns its empty state,
        // and a teacher between timetables still needs the way in.
        if (role && role !== 'student') {
          var staff = { href: '/teacher/classes.html', label: 'My classes',
                        title: 'Your classes' };
          cacheSet(cacheKey, staff);
          return staff;
        }

        /* We are on a staff surface and the viewer is a student — so we
           deliberately did not ask about their membership, and we do not know
           it. Render nothing (the guard on this page is about to send them
           home anyway) and CACHE NOTHING: writing a null here would answer
           "no class" for the next half hour on the KS3 lesson pages too,
           which is the entry disappearing from the one place it matters. */
        if (!wantMembership) { return null; }

        var ids = (memberRows || []).map(function (r) { return r.class_id; })
                                    .filter(Boolean);
        if (!ids.length) { cacheSet(cacheKey, null); return null; }

        // Second hop rather than a PostgREST embed: `!inner` plus an embedded
        // `deleted_at=is.null` filter is the fiddlier syntax of the two and
        // this one cannot silently return the wrong shape.
        var list = ids.map(encodeURIComponent).join(',');

        // Year-scope (MRB-261). Without this a Year 11 signing in today is
        // offered a choice between 11r/Sc1 and the 10R1 they left in July —
        // MRB-237 deliberately kept last year's membership rows so the record
        // of what they were taught in Year 10 survives, and the fix belongs
        // here in the view rather than in the data.
        var working = workingAcademicYear(yearRows);
        var yearFilter = working
          ? '&academic_year_id=eq.' + encodeURIComponent(working.id)
          : '';                       // no years readable (self-serve visitor
                                      // with no school) -> don't hide anything

        return rest(conf, session,
                    'classes?id=in.(' + list + ')&deleted_at=is.null' +
                    yearFilter +
                    '&select=id,name&order=name.asc')
          .then(function (classes) {
            classes = classes || [];
            if (!classes.length) { cacheSet(cacheKey, null); return null; }

            var entry;
            if (classes.length === 1) {
              // Straight to it. The uuid is already in the href — the student
              // never sees it, never types it, and never meets a picker they
              // have no choice to make on.
              entry = {
                href: '/student/class.html?class=' +
                      encodeURIComponent(classes[0].id),
                label: 'My class',
                title: classes[0].name || 'Your class'
              };
            } else {
              // KS4 triple students may legitimately hold several.
              entry = {
                href: '/student/classes.html',
                label: 'My classes',
                title: classes.length + ' classes'
              };
            }
            cacheSet(cacheKey, entry);
            return entry;
          });
      });
    })();
    return _inflight;
  }

  // ── Rendering ───────────────────────────────────────────────────────────

  // Don't offer a link to the page the viewer is already on. Compared on
  // pathname only, because the single-class href carries ?class=<uuid> and the
  // student IS on that page once they arrive.
  function isHere(href) {
    var path = href.split('?')[0];
    return window.location.pathname === path;
  }

  function anchor(cls, entry) {
    var a = document.createElement('a');
    a.className = cls;
    a.href = entry.href;
    a.textContent = entry.label;
    a.title = entry.title;
    a.setAttribute('data-mrb-class-entry', '1');
    return a;
  }

  // 1. KS3 — its own design world. An outlined lozenge sitting immediately
  //    before the solid ink KS3 pill: same lozenge geometry, different weight,
  //    so the two read as a pair without competing. No new colour (every value
  //    is an existing --ks3-* token), which is what keeps the MRB-183 parity
  //    gate's provenance layer green.
  function renderKs3(entry) {
    var rail = document.querySelector('.ks3-nav-rail');
    if (!rail) return false;
    var pill = rail.querySelector('.ks3-pill');
    var a = anchor('ks3-classlink', entry);
    if (pill) rail.insertBefore(a, pill);
    else rail.appendChild(a);
    return true;
  }

  // 2. Public / KS4 — into the persistent cluster, before the auth control,
  //    plus a drawer row. .nav-class-link collapses one rung ABOVE
  //    .nav-text-link (see shared/nav.css) so the measured 600px ladder that
  //    3D Studio was fitted to is left exactly as it was tested.
  function renderPublic(entry) {
    var cluster = document.querySelector('.nav-cluster');
    if (!cluster) return false;
    var authArea = cluster.querySelector('#nav-auth-area');
    var a = anchor('nav-class-link', entry);
    if (authArea) cluster.insertBefore(a, authArea);
    else cluster.appendChild(a);

    // Drawer row, first in the menu — below the collapse breakpoints this is
    // the only place the entry lives, so it leads rather than trails. nav.js
    // built the drawer on DOMContentLoaded; we are past a network round trip,
    // so it exists. If it somehow doesn't, the cluster link above still does.
    var menu = document.querySelector('#nav-drawer .nav-drawer-menu');
    if (menu && !menu.querySelector('[data-mrb-class-entry]')) {
      var d = document.createElement('a');
      d.href = entry.href;
      d.title = entry.title;
      d.setAttribute('data-mrb-class-entry', '1');
      d.innerHTML = '<span class="nav-drawer-ico">🎒</span>';
      d.appendChild(document.createTextNode(entry.label));
      menu.insertBefore(d, menu.firstChild);
      // nav.js wires "close on link click" over the rows that existed when it
      // ran, so this one wires its own.
      d.addEventListener('click', function () {
        var burger = document.querySelector('.nav-burger');
        if (burger && burger.getAttribute('aria-expanded') === 'true') burger.click();
      });
    }
    return true;
  }

  // 3. Dashboards — plain text link in the right-hand group, matching the
  //    utilitarian styling the brand rule pins for these pages (no logo asset,
  //    muted text). Inserted before the env pill's siblings rather than after,
  //    so Sign out stays last where every dashboard already puts it.
  function renderDashboard(entry) {
    var nav = document.querySelector('nav.top-nav');
    if (!nav) return false;
    var group = nav.querySelector('div');
    if (!group) return false;
    var a = anchor('', entry);
    a.style.cssText = 'color:var(--muted);font-weight:700;font-size:0.85rem;' +
                      'text-decoration:none;white-space:nowrap;';
    a.textContent = '🎒 ' + entry.label;
    group.insertBefore(a, group.firstChild);
    return true;
  }

  function mount() {
    resolve().then(function (entry) {
      if (!entry) return;                 // signed out, or zero classes
      if (isHere(entry.href)) return;     // already here
      renderKs3(entry) || renderPublic(entry) || renderDashboard(entry);
    }).catch(function () { /* never break a page over a nav affordance */ });
  }

  /* ⊕ MRB-267 — `workingAcademicYear` is exported because it is the KEY
     STAGE'S ONE ANSWER to "which year are we working in", and it was
     previously answered by three hand-synced copies that had already drifted
     apart cosmetically. See the block comment above it: never `is_current`,
     which is moved by hand on 1 September, and never a bare `end_date >=
     today`, because academic years run to 31 August and through the summer
     two of them are unfinished at once. */
  window.MRBClassEntry = {
    resolve: resolve,
    mount: mount,
    workingAcademicYear: workingAcademicYear,
    /* ⊕ 27 Aug 2026 — the ROWS the predicate above is applied to, read once
       per page and shared with both data layers. Resolves to null when it
       cannot know (signed out, or the read failed); a caller must fall back
       to its own query rather than reading null as "no years". */
    academicYears: academicYears,
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', mount);
  } else {
    mount();
  }
})();
