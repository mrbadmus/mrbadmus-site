# Run
# ═══════════════════════════════════════════════════════════════════════════

def main(argv):
    print("\nrainford_ks3_sow — Rainford High School's KS3 scheme of work")
    print("=" * 70)

    if "--verify-source" in argv:
        print("\n  Verifying ENTRIES against the workbook…")
        return verify_source()

    lessons = platform_lessons()
    check_consistency(lessons)
    blocks = build_rows(lessons)
    check_ceiling(blocks)
    report(blocks, lessons)

    if "--report" in argv:
        return 0

    os.makedirs(SEED_DIR, exist_ok=True)
    path = os.path.join(SEED_DIR, SEED_FILE)
    with open(path, "w", encoding="utf-8") as f:
        f.write(render(blocks, lessons))
    print("\n  → %s" % path)
    print("\n  ⚠️ This file and supabase/seeds/20260726182000_ks3_school_"
          "schemes.sql\n     both own Rainford's KS3 override rows. Apply "
          "exactly one. OPEN ON MIDE.\n")
    return 0


